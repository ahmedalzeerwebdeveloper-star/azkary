def flatten_azkar(azkar_list):
    res = []
    for item in azkar_list:
        if isinstance(item, list):
            res.extend(item)
        elif isinstance(item, dict):
            res.append(item)
    return res

def parse_count(c):
    try:
        return int(c)
    except:
        return 1

# --- Morning Adhkar ---
