def apply_diacritics(text):
    stripped = text.replace('(', '').replace(')', '').strip()
    for k, v in diacritics_map.items():
        if stripped == k.strip():
            return v
    res = text
    for k, v in sorted(diacritics_map.items(), key=lambda x: len(x[0]), reverse=True):
        if k in res:
            res = res.replace(k, v)
    return res

